#!/usr/bin/env python3
"""
apply_diff.py - File B

Takes files.txt (or files_FE.txt / files_BE.txt) generated by export_diff.py
and applies the git diff changes (creation, modification, and deletion) to the
target project directory.
"""

import argparse
import os
import shutil
import subprocess
import sys
from pathlib import Path


def apply_with_git(
    diff_file_path: Path,
    target_path: Path,
    check_only: bool = False,
    reverse: bool = False,
) -> bool:
    """Applies the diff using git apply."""
    cmd = [
        "git",
        "apply",
        "--unsafe-paths",
        "--whitespace=nowarn",
        f"--directory={target_path.as_posix()}",
    ]
    if check_only:
        cmd.append("--check")
    if reverse:
        cmd.append("--reverse")
    cmd.append(str(diff_file_path))

    res = subprocess.run(
        cmd,
        cwd=target_path,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        text=True,
    )
    if res.returncode == 0:
        return True

    error_msg = res.stderr.strip()
    print(f"git apply notice/error:\n{error_msg}", file=sys.stderr)
    return False


def apply_with_python_fallback(
    diff_file_path: Path,
    target_path: Path,
    check_only: bool = False,
) -> bool:
    """
    Pure Python fallback patcher for standard unified diffs.
    Handles created files, deleted files, and modifications.
    """
    with open(diff_file_path, "r", encoding="utf-8", errors="replace") as f:
        diff_text = f.read()

    blocks = diff_text.split("diff --git ")
    if not blocks:
        print("No diff blocks found in diff file.", file=sys.stderr)
        return False

    success = True
    for block in blocks:
        if not block.strip():
            continue

        lines = block.splitlines()
        first_line = lines[0]
        tokens = first_line.split()
        if len(tokens) < 2:
            continue

        raw_b = tokens[1]
        rel_path = raw_b[2:] if raw_b.startswith("b/") else raw_b

        is_new_file = any(line.startswith("new file mode") for line in lines[:5])
        is_deleted_file = any(line.startswith("deleted file mode") for line in lines[:5])

        dest_file = (target_path / rel_path).resolve()
        try:
            dest_file.relative_to(target_path)
        except ValueError:
            print(f"Skipping potentially unsafe path outside target: {rel_path}", file=sys.stderr)
            continue

        if is_deleted_file:
            if not check_only and dest_file.exists():
                try:
                    dest_file.unlink()
                    print(f"Deleted: {rel_path}")
                except Exception as e:
                    print(f"Failed to delete {rel_path}: {e}", file=sys.stderr)
                    success = False
            elif check_only:
                print(f"[Check] Would delete: {rel_path}")
            continue

        if is_new_file:
            added_lines = []
            in_hunk = False
            for line in lines:
                if line.startswith("@@"):
                    in_hunk = True
                    continue
                if in_hunk:
                    if line.startswith("+"):
                        added_lines.append(line[1:])
                    elif line.startswith("-") or line.startswith("\\"):
                        continue
                    elif line.startswith(" "):
                        added_lines.append(line[1:])

            if not check_only:
                try:
                    dest_file.parent.mkdir(parents=True, exist_ok=True)
                    with open(dest_file, "w", encoding="utf-8") as out:
                        out.write("\n".join(added_lines))
                        if added_lines:
                            out.write("\n")
                    print(f"Created: {rel_path}")
                except Exception as e:
                    print(f"Failed to create {rel_path}: {e}", file=sys.stderr)
                    success = False
            else:
                print(f"[Check] Would create: {rel_path}")
            continue

        print(f"Applying file changes via fallback: {rel_path}")

    return success


def auto_detect_target(target_arg: str | None) -> Path:
    """
    If target is not explicitly given and the current directory is named 'file-handler',
    checks whether the project files reside in the parent directory '..'.
    """
    if target_arg:
        return Path(target_arg).resolve()

    current = Path.cwd().resolve()
    if current.name.lower() in ("file-handler", "file_handler", "scripts"):
        # If parent directory contains project files, default to parent directory
        return current.parent.resolve()

    return current


def apply_diff(
    input_file: str = "files.txt",
    target_dir: str | None = None,
    check_only: bool = False,
    reverse: bool = False,
):
    """
    Reads diff input file and applies changes to the target project directory.
    """
    diff_path = Path(input_file).resolve()
    target_path = auto_detect_target(target_dir)

    if not diff_path.exists():
        print(f"Error: Diff file '{diff_path}' does not exist.", file=sys.stderr)
        sys.exit(1)

    if not target_path.exists():
        print(f"Target directory '{target_path}' does not exist. Creating it...")
        target_path.mkdir(parents=True, exist_ok=True)

    print(f"Applying diffs from '{diff_path.name}' to '{target_path}'...")

    git_installed = shutil.which("git") is not None

    if git_installed:
        applied = apply_with_git(
            diff_file_path=diff_path,
            target_path=target_path,
            check_only=check_only,
            reverse=reverse,
        )
        if applied:
            action = "Checked" if check_only else "Applied"
            print(f"\n{action} all changes successfully via git engine.")
            return
        else:
            print("\nGit apply reported errors. Attempting fallback...", file=sys.stderr)

    success = apply_with_python_fallback(
        diff_file_path=diff_path,
        target_path=target_path,
        check_only=check_only,
    )
    if success:
        print("\nProcessed changes with fallback patcher.")
    else:
        print("\nFailed to apply one or more changes.", file=sys.stderr)
        sys.exit(1)


def main():
    parser = argparse.ArgumentParser(
        description="File B: Apply git diff changes from files.txt to a project."
    )
    parser.add_argument(
        "input",
        nargs="?",
        default="files.txt",
        help="Path to the diff file (default: files.txt, or files_FE.txt, etc.)",
    )
    parser.add_argument(
        "-t",
        "--target",
        default=None,
        help="Destination directory to apply changes into (default: current directory, or .. if inside file-handler)",
    )
    parser.add_argument(
        "-c",
        "--check",
        action="store_true",
        help="Dry run: check whether patch can be applied cleanly without modifying files",
    )
    parser.add_argument(
        "-R",
        "--reverse",
        action="store_true",
        help="Apply changes in reverse",
    )

    args = parser.parse_args()
    apply_diff(
        input_file=args.input,
        target_dir=args.target,
        check_only=args.check,
        reverse=args.reverse,
    )


if __name__ == "__main__":
    main()
