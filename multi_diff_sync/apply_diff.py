#!/usr/bin/env python3
"""
apply_diff.py - Multi-Folder Git Diff Applier (Two-Operation Engine: CREATE & DELETE)

Takes files_<folder>.txt or files.txt (generated by export_diff.py) and applies
the packaged changes directly into the corresponding target project directory.

Only 2 operations:
1. CREATE: Blatantly writes/overwrites the entire file with the packaged content.
2. DELETE: Deletes the file if it exists in the target directory.

Does NOT rely on 'git apply', git commit hashes, or matching git trees.
Safe, robust, and completely portable across different repositories.
"""

import argparse
import base64
import os
import re
import sys
from pathlib import Path

DEFAULT_IGNORE_DIRS = {
    'node_modules',
    'reports',
    'dist',
    '.git',
    '__pycache__',
    '.venv',
    'venv',
    'build',
    '.vscode',
    'public',
    '.next',
}

DEFAULT_IGNORE_FILES = {
    'package-lock.json',
    'test.py',
    'files.txt',
    'files_FE.txt',
    'files_BE.txt',
    'final.txt',
    '.DS_Store',
}


def is_ignored(rel_path: str, ignore_dirs: set[str], ignore_files: set[str]) -> bool:
    """Checks if rel_path matches any ignored directory or ignored filename."""
    path = Path(rel_path)
    for part in path.parts[:-1]:
        if part in ignore_dirs:
            return True
    if len(path.parts) == 1 and path.name in ignore_dirs:
        return True
    if path.name in ignore_files:
        return True
    return False


def resolve_target_dir(target_arg: str | None, input_file_path: Path) -> Path:
    """
    Intelligently determines the target directory:
    - If explicitly provided via -t, resolves and uses it.
    - Handles standalone separate projects where FE or BE is its own repository:
        e.g. running from /path/to/BE/file-handler -> targets /path/to/BE
    - Handles monorepos where FE, BE, and file-handler are siblings:
        e.g. running from /repo/file-handler with files_FE.txt -> targets /repo/FE
    - If running from inside 'file-handler' or 'scripts':
        defaults to parent directory '..'.
    - Defaults to current directory '.'.
    """
    if target_arg:
        return Path(target_arg).resolve()

    current = Path.cwd().resolve()
    filename = input_file_path.name
    is_in_file_handler = current.name.lower() in ("file-handler", "file_handler", "scripts")

    # Check for files_<folder>.txt naming convention
    m = re.match(r"^files_(.+?)\.txt$", filename, re.IGNORECASE)
    if m:
        folder_name = m.group(1)

        # Case A: Standalone project where current directory or parent directory matches folder name
        # e.g. /my-project/BE/file-handler -> current.parent is 'BE' -> target is /my-project/BE
        if is_in_file_handler and current.parent.name.upper() == folder_name.upper():
            return current.parent.resolve()
        if current.name.upper() == folder_name.upper():
            return current

        # Case B: Monorepo where FE and BE are sibling directories to file-handler
        candidates = [
            (current.parent / folder_name).resolve() if is_in_file_handler else (current / folder_name).resolve(),
            (current / folder_name).resolve(),
        ]
        for c in candidates:
            if c.exists() and c.is_dir() and c != current:
                return c

        # Case C: Standalone project named differently (e.g. rwa-backend/file-handler)
        if is_in_file_handler:
            return current.parent.resolve()

    # Generic files.txt running from file-handler
    if is_in_file_handler:
        return current.parent.resolve()

    return current



def apply_single_package(
    diff_path: Path,
    target_path: Path,
    check_only: bool = False,
    overwrite: bool = True,
    ignore_dirs: set[str] | None = None,
    ignore_files: set[str] | None = None,
) -> bool:
    """Applies CREATE and DELETE operations from a single package file into target_path."""
    if ignore_dirs is None:
        ignore_dirs = set(DEFAULT_IGNORE_DIRS)
    if ignore_files is None:
        ignore_files = set(DEFAULT_IGNORE_FILES)

    if not diff_path.exists():
        print(f"Error: Diff file '{diff_path}' does not exist.", file=sys.stderr)
        return False

    if not target_path.exists():
        if check_only:
            print(f"[Check] Target directory '{target_path}' does not exist (would be created).")
        else:
            print(f"Target directory '{target_path}' does not exist. Creating it...")
            target_path.mkdir(parents=True, exist_ok=True)

    with open(diff_path, "r", encoding="utf-8", errors="replace") as f:
        content = f.read()

    header_pattern = re.compile(r"^=== (.+?) ===$", re.MULTILINE)
    matches = list(header_pattern.finditer(content))

    if not matches:
        print(f"Notice: No file changes found in '{diff_path.name}'.")
        return True

    mode_label = "DRY RUN (Check only)" if check_only else "APPLYING CHANGES"
    print(f"\n[{mode_label}] From '{diff_path.name}' -> Target: '{target_path}'")
    print(f"Total operations in package: {len(matches)}\n")

    created_count = 0
    deleted_count = 0
    skipped_count = 0
    error_count = 0

    for i, match in enumerate(matches):
        raw_header = match.group(1).strip()

        if raw_header.startswith("DELETE:"):
            op = "DELETE"
            rel_path = raw_header[len("DELETE:"):].strip()
        elif raw_header.startswith("CREATE_BASE64:"):
            op = "CREATE_BASE64"
            rel_path = raw_header[len("CREATE_BASE64:"):].strip()
        elif raw_header.startswith("CREATE:"):
            op = "CREATE"
            rel_path = raw_header[len("CREATE:"):].strip()
        else:
            op = "CREATE"
            rel_path = raw_header

        if is_ignored(rel_path, ignore_dirs, ignore_files):
            print(f"  [Ignored]  {rel_path}")
            skipped_count += 1
            continue

        dest_file = (target_path / rel_path).resolve()

        # Security check: prevent directory traversal
        try:
            dest_file.relative_to(target_path)
        except ValueError:
            print(f"  [Security] Skipping unsafe path outside target: {rel_path}", file=sys.stderr)
            error_count += 1
            continue

        start_idx = match.end()
        if start_idx < len(content) and content[start_idx] == "\n":
            start_idx += 1
        end_idx = matches[i + 1].start() if i + 1 < len(matches) else len(content)
        block_content = content[start_idx:end_idx]

        if block_content in ("\n\n", "\n"):
            block_content = ""
        elif block_content.endswith("\n\n"):
            block_content = block_content[:-1]

        if op == "DELETE":
            if dest_file.exists():
                if check_only:
                    print(f"  [Check: DELETE]  {rel_path}")
                else:
                    try:
                        dest_file.unlink()
                        print(f"  [DELETED]        {rel_path}")
                    except Exception as e:
                        print(f"  [ERROR] Failed to delete '{rel_path}': {e}", file=sys.stderr)
                        error_count += 1
                        continue
                deleted_count += 1
            else:
                if check_only:
                    print(f"  [Check: DELETE]  {rel_path} (already absent)")
                else:
                    print(f"  [DELETED]        {rel_path} (already absent)")
                deleted_count += 1

        elif op in ("CREATE", "CREATE_BASE64"):
            if dest_file.exists() and not overwrite:
                print(f"  [Skipped]        {rel_path} (already exists, overwrite=False)")
                skipped_count += 1
                continue

            action_desc = "OVERWRITE" if dest_file.exists() else "CREATE"

            if check_only:
                print(f"  [Check: {action_desc}] {rel_path}")
                created_count += 1
                continue

            try:
                dest_file.parent.mkdir(parents=True, exist_ok=True)
                if op == "CREATE_BASE64":
                    binary_data = base64.b64decode(block_content.strip())
                    with open(dest_file, "wb") as out:
                        out.write(binary_data)
                else:
                    with open(dest_file, "w", encoding="utf-8") as out:
                        out.write(block_content)
                print(f"  [{action_desc}D]       {rel_path}")
                created_count += 1
            except Exception as e:
                print(f"  [ERROR] Failed writing '{rel_path}': {e}", file=sys.stderr)
                error_count += 1

    print(f"\nSummary for '{diff_path.name}':")
    print(f"  Created/Updated: {created_count}")
    print(f"  Deleted:         {deleted_count}")
    print(f"  Skipped/Ignored: {skipped_count}")
    if error_count > 0:
        print(f"  Errors:          {error_count}")

    return error_count == 0


def main():
    parser = argparse.ArgumentParser(
        description="Multi-Folder Git Diff Applier using CREATE and DELETE operations."
    )
    parser.add_argument(
        "input",
        nargs="?",
        default=None,
        help="Path to diff file (e.g. files_FE.txt, files_BE.txt, files.txt). If omitted, scans for files_*.txt",
    )
    parser.add_argument(
        "-t",
        "--target",
        default=None,
        help="Destination directory (auto-detected if omitted)",
    )
    parser.add_argument(
        "-c",
        "--check",
        action="store_true",
        help="Dry run: inspect what changes would be applied without modifying files",
    )
    parser.add_argument(
        "--no-overwrite",
        action="store_true",
        help="Do not overwrite existing files",
    )
    parser.add_argument(
        "--ignore-dirs",
        help="Comma-separated directories to ignore (overrides defaults)",
    )
    parser.add_argument(
        "--ignore-files",
        help="Comma-separated filenames to ignore (overrides defaults)",
    )
    parser.add_argument(
        "--add-ignore-dirs",
        help="Comma-separated additional directories to ignore (appends to defaults)",
    )
    parser.add_argument(
        "--add-ignore-files",
        help="Comma-separated additional filenames to ignore (appends to defaults)",
    )

    args = parser.parse_args()

    ignore_dirs = set(DEFAULT_IGNORE_DIRS)
    if args.ignore_dirs:
        ignore_dirs = {d.strip() for d in args.ignore_dirs.split(",") if d.strip()}
    if args.add_ignore_dirs:
        ignore_dirs.update(d.strip() for d in args.add_ignore_dirs.split(",") if d.strip())

    ignore_files = set(DEFAULT_IGNORE_FILES)
    if args.ignore_files:
        ignore_files = {f.strip() for f in args.ignore_files.split(",") if f.strip()}
    if args.add_ignore_files:
        ignore_files.update(f.strip() for f in args.add_ignore_files.split(",") if f.strip())

    current = Path.cwd().resolve()
    overall_success = True

    # If input is provided explicitly:
    if args.input:
        input_path = Path(args.input).resolve()
        target_path = resolve_target_dir(args.target, input_path)
        success = apply_single_package(
            diff_path=input_path,
            target_path=target_path,
            check_only=args.check,
            overwrite=not args.no_overwrite,
            ignore_dirs=ignore_dirs,
            ignore_files=ignore_files,
        )
        if not success:
            overall_success = False
    else:
        # Auto-detect all files_<folder>.txt in current directory
        discovered = sorted(current.glob("files_*.txt"))
        if not discovered:
            default_file = current / "files.txt"
            if default_file.exists():
                discovered = [default_file]

        if not discovered:
            print("No diff files (files_*.txt or files.txt) found in the current directory.", file=sys.stderr)
            print("Usage: python apply_diff.py [files_<folder>.txt] [-t <target_dir>]", file=sys.stderr)
            sys.exit(1)

        print(f"Auto-discovered diff packages: {[f.name for f in discovered]}")
        for pkg in discovered:
            target_path = resolve_target_dir(args.target, pkg)
            success = apply_single_package(
                diff_path=pkg,
                target_path=target_path,
                check_only=args.check,
                overwrite=not args.no_overwrite,
                ignore_dirs=ignore_dirs,
                ignore_files=ignore_files,
            )
            if not success:
                overall_success = False

    if not overall_success:
        sys.exit(1)


if __name__ == "__main__":
    main()
